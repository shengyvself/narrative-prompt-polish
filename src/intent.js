/**
 * full 模式末尾润色指令：按意图选择组织结构（保持会话 system 原样以命中 prompt cache，
 * 意图结构全部折进最后一条 user message —— 前缀不变才不吃掉缓存）。
 * @param {Intent} intent
 */
export function polishInstruction(intent) {
  const structure = {
    debug: '按「环境与上下文 → 实际现象 → 预期行为 → 重点核查方向 → 根因+修复」组织。',
    implement: '按「目标与交付物 → 技术栈与约束 → 执行步骤 → 验收标准 → 输出格式」组织。',
    explain: '按「话题范围与目标读者 → 需覆盖的维度 → 依据、例子或对比」组织。',
    chat: '把模糊表达具体化，保留原意，不增删事实。',
  }[intent]
  return [
    '<polish-request>请把上一条 user 消息改写得更清晰、更具体、更适合交给 AI Agent 执行。要求：',
    "(1) 保留所有事实（文件名/报错/版本/技术栈/URL/代码）；",
    "(2) 把模糊表达换成具体动作和可验证结果；",
    "(3) 如果上下文没给关键信息，标注\"请结合项目代码/日志确认\"；",
    "(4) 与用户同语言；",
    "(5) 只输出改写后的文本，不要解释/引号/代码围栏。",
    structure,
    '</polish-request>'
  ].join('\n')
}

/**
 * 本地意图分类：按 INTENT_SIGNALS 顺序首中即返回，兜底 chat。
 * @param {string} draft
 * @returns {Intent}
 */
export function classifyIntent(draft) {
  const entries = /** @type {[Intent, RegExp[]][]} */ (Object.entries(INTENT_SIGNALS))
  for (const [intent, patterns] of entries) {
    if (patterns.some(p => p.test(draft))) return intent
  }
  return 'chat'
}